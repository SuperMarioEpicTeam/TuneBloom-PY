import unittest

from tunebloom.nwlib.dsp_encode import encode_dsp_adpcm
from tunebloom.nwlib.dsp_adpcm import (
    decode_dsp_adpcm, dsp_adpcm_bytes_for_samples, get_dsp_adpcm_loop_context,
)


class DspEncodeTests(unittest.TestCase):
    def test_encoder_matches_cpp_golden_37_samples(self):
        pcm = [((i * 7919 + 12345) % 40001) - 20000 for i in range(37)]
        result = encode_dsp_adpcm(pcm)
        self.assertEqual(
            result.data.hex(),
            "3bc027a1c2791c271b9fd279fd178fc11b68ec168ece",
        )
        self.assertEqual(result.coefficients, (
            (-61, -959), (146, -810), (0, 0), (181, -1067),
            (0, 0), (0, 0), (0, 0), (0, 0),
        ))

    def test_encoder_matches_cpp_golden_100_samples(self):
        pcm = [((i * 7919 + 12345) % 40001) - 20000 for i in range(100)]
        result = encode_dsp_adpcm(pcm)
        self.assertEqual(
            result.data.hex(),
            "6bc12791d2781d270bafc179eb179eb14b69eb068eb068eb5c13bdf13bdf135d0c1f25e1f25e1f253cb2023b2023b2021b791f3781f3781e3b36",
        )
        self.assertEqual(len(result.data), dsp_adpcm_bytes_for_samples(100))

    def test_encoder_matches_cpp_for_silent_and_sparse_signals(self):
        cases = [
            ([0] * 14, "0000000000000000"),
            ([1] + [0] * 13, "0010000000000000"),
            ([0] * 13 + [1], "0000000000000001"),
        ]
        for pcm, expected in cases:
            with self.subTest(pcm=pcm):
                self.assertEqual(encode_dsp_adpcm(pcm).data.hex(), expected)

    def test_encoder_matches_cpp_when_coefficient_matrix_is_singular(self):
        pcm = [((i * 1237) % 30001) - 15000 for i in range(101)]
        result = encode_dsp_adpcm(pcm)
        self.assertEqual(
            result.data.hex(),
            "6b9ffffff00000014b122344556779aa38755555545555450b34456679eaabcc38555545555545550b6679eaabbcddef38155555455554554b9aa0",
        )
        self.assertEqual(result.coefficients, (
            (649, -740), (1917, -128), (1608, -218), (2048, 0),
            (0, 0), (0, 0), (1658, -166), (0, 0),
        ))

    def test_encode_decode_produces_valid_pcm(self):
        pcm = [((i * 3571) % 30001) - 15000 for i in range(70)]
        encoded = encode_dsp_adpcm(pcm)
        decoded = decode_dsp_adpcm(
            encoded.data, encoded.coefficients, encoded.predictor_scale,
            encoded.yn1, encoded.yn2, len(pcm),
        )
        self.assertEqual(len(decoded), len(pcm))
        self.assertTrue(all(-32768 <= value <= 32767 for value in decoded))

    def test_loop_context_uses_last_decoded_frame_header(self):
        pcm = [((i * 7919 + 12345) % 40001) - 20000 for i in range(37)]
        encoded = encode_dsp_adpcm(pcm)
        context = get_dsp_adpcm_loop_context(
            encoded.data, encoded.coefficients, encoded.predictor_scale,
            encoded.yn1, encoded.yn2, 23,
        )
        # Golden context generated by TuneBloom's original getLoopContext().
        self.assertEqual(context, (27, 5640, -344))


if __name__ == "__main__":
    unittest.main()
